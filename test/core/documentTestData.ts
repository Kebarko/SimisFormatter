/**
 * A case of the parse-and-save test, ported from SimisSharp's `SimisDocumentTestData`.
 */
export interface DocumentTestCase {
    /**
     * A short description of the case, used as the name of the test.
     */
    name: string;

    /**
     * The text to parse.
     */
    input: string;

    /**
     * The text that writing the parsed document is expected to give.
     */
    expected: string;

    /**
     * The writer options, or undefined for the defaults, as SimisSharp passes `null`.
     */
    options?: WriterOptions;
}

/**
 * Joins lines with CRLF without a final line break, as a C# raw string literal in a source file with CRLF line endings does.
 * Each argument is one line of the raw string literal in SimisSharp's test data, so a final empty argument makes the text end with a line break.
 * @param sourceLines The lines of the raw string literal.
 * @returns The text.
 */
function text(...sourceLines: string[]): string {
    return sourceLines.join(CRLF);
}

